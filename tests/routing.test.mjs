import test from 'node:test';
import assert from 'node:assert/strict';

test('skip fragment reload renders the app, changes language, and preserves lesson routes on skip',async()=>{
 const saved=Object.fromEntries(['window','document','location','history'].map(k=>[k,globalThis[k]]));
 let appHTML='';let prevented=false;let focused=false;const clicks=[];const windowEvents={};
 const main={focus(){focused=true;}};
 const app={set innerHTML(value){appHTML=value;},get innerHTML(){return appHTML;}};
 const skip={textContent:''};
 globalThis.location={hash:'#main'};
 globalThis.history={replaceState(_a,_b,hash){location.hash=hash;}};
 globalThis.window={localStorage:{getItem:()=>null,setItem(){}},addEventListener(k,fn){windowEvents[k]=fn;},scrollTo(){},scrollY:0};
 globalThis.document={documentElement:{lang:''},title:'',querySelector(s){return {'#app':app,'.skip':skip,'#main':main}[s]??null;},addEventListener(k,fn){if(k==='click')clicks.push(fn);}};
 try{
  await import('../dist/app.mjs?routing-regression');
  assert.ok(appHTML.includes('class="app-header"'),'#main reload must not leave a blank app');
  const footer=()=>appHTML.match(/<nav class="bottom-nav[\s\S]*?<\/nav>/)?.[0]??'';
  assert.equal((footer().match(/<a /g)||[]).length,5,'footer provides the five requested destinations');
  for(const label of ['HOME','FISIOLOGIA','CLÍNICA','CÂMARA','OPERAÇÃO'])assert.ok(footer().includes(label));
  assert.ok(appHTML.includes('class="brand-logo"'));
  assert.ok(appHTML.includes('href="#notifications"'));
  assert.ok(appHTML.includes('href="#profile"'));
  assert.ok(appHTML.includes('/fisiologia"'),'Home provides the Fisiologia card');
  assert.ok(appHTML.includes('/operacao"'),'Home provides the Operação card');
  location.hash='#chamber';windowEvents.hashchange();
  assert.ok(appHTML.includes('#module/01/chamber'));
  assert.ok(appHTML.includes('#module/06/chamber'));
  assert.ok(!appHTML.includes('#module/19/'));
  assert.ok(appHTML.includes('href="#lab"'),'laboratory remains reachable through chamber');
  location.hash='#indications';windowEvents.hashchange();
  assert.ok(appHTML.includes('#indication/radiation-cystitis'));
  assert.ok(!appHTML.includes('href="#module/'),'the removed chapter block does not appear in Indications');
  location.hash='#module/13/indications';windowEvents.hashchange();
  assert.ok(appHTML.includes('#lesson/honey/indications'));
  location.hash='#lesson/honey/indications';windowEvents.hashchange();
  assert.ok(appHTML.includes('href="#module/13/indications"'),'lesson Back retains its module and category');
  assert.ok(/href="\/(?:oxygenna\/)?clinica" class="active"/.test(footer()));
  location.hash='#protocols';windowEvents.hashchange();
  assert.ok(appHTML.includes('#protocol/severe-anemia'));
  assert.ok(appHTML.includes('#protocol/decompression'));
  assert.ok(!appHTML.includes('href="#module/'),'the removed chapter block does not appear in Protocols');
  location.hash='#notifications';windowEvents.hashchange();
  assert.ok(appHTML.includes('data-read-notices'));
  const read={dataset:{},hasAttribute:name=>name==='data-read-notices'};
  for(const click of clicks)click({target:{closest:s=>s==='button'?read:null},preventDefault(){}});
  assert.ok(appHTML.includes('Todas as atualizações foram lidas.'));
  assert.ok(!appHTML.includes('class="notification-dot"'));
  location.hash='#home';windowEvents.hashchange();
  const language={dataset:{lang:'en'},hasAttribute:()=>false};
  for(const click of clicks)click({target:{closest:s=>s==='button'?language:null},preventDefault(){}});
  assert.ok(appHTML.includes('Science under pressure.'),'language must rerender after a #main reload');
  location.hash='#lesson/honey';windowEvents.hashchange();
  assert.ok(appHTML.includes('HONEY: separate the outcomes'));
  const previous=location.hash;
  for(const click of clicks)click({target:{closest:s=>s==='.skip'?skip:null},preventDefault(){prevented=true;}});
  assert.ok(prevented,'skip link must bypass route navigation');
  assert.equal(location.hash,previous);assert.ok(focused);
  location.hash='#track/clinical';windowEvents.hashchange();
  assert.ok(!/<main[^>]+class="track"/.test(appHTML),'detail page must not inherit the horizontal track-card layout');
  location.hash='#learn';windowEvents.hashchange();
  const explore={dataset:{},hasAttribute:name=>name==='data-explore'};
  for(const click of clicks)click({target:{closest:s=>s==='button'?explore:null},preventDefault(){}});
  assert.equal(location.hash,'#curriculum','Explore pathways opens the structured learning map');
  windowEvents.hashchange();
  assert.ok(appHTML.includes('Medicine and diving'));
  assert.ok(appHTML.includes('#module/19'));
  assert.ok(appHTML.includes('13 initial syntheses available'));
  location.hash='#module/19';windowEvents.hashchange();
  assert.ok(appHTML.includes('Decompression sickness and gas embolism'));
  assert.ok(appHTML.includes('#lesson/dci'));
  assert.ok(appHTML.includes('#lesson/dci/all'),'a lesson opened from the complete index retains that index context');
  assert.ok(appHTML.includes('#module/17'));
  const spanish={dataset:{lang:'es'},hasAttribute:()=>false};
  for(const click of clicks)click({target:{closest:s=>s==='button'?spanish:null},preventDefault(){}});
  assert.ok(appHTML.includes('Enfermedad descompresiva y embolia gaseosa'));
  location.hash='#curriculum/path-diving';windowEvents.hashchange();
  assert.ok(appHTML.includes('#module/16'));
  assert.ok(!appHTML.includes('#module/09'),'focused diving path excludes unrelated medicine modules');
  assert.ok(appHTML.includes('#module/07/path-diving'),'module links preserve the chosen pathway');
  location.hash='#module/07/path-diving';windowEvents.hashchange();
  assert.ok(appHTML.includes('#module/16/path-diving'),'diving pathway continues from module 07 to 16');
  assert.ok(!appHTML.includes('#module/08'),'diving pathway does not navigate into excluded module 08');
  assert.ok(appHTML.includes('href="#curriculum/path-diving"'),'Back returns to the chosen pathway');
  location.hash='#module/19/path-medicine';windowEvents.hashchange();
  assert.ok(appHTML.includes('#module/23/path-medicine'),'medicine pathway continues from module 19 to 23');
  assert.ok(!appHTML.includes('#module/20'),'medicine pathway does not navigate into excluded module 20');
  location.hash='#curriculum/pressure';windowEvents.hashchange();
  for(const click of clicks)click({target:{closest:s=>s==='button'?language:null},preventDefault(){}});
  assert.ok(appHTML.includes('3 initial syntheses available'),'filtered maps count only their available lessons');
  location.hash='#curriculum/path-diving';windowEvents.hashchange();
  assert.ok(appHTML.includes('11 initial syntheses available'),'focused maps count their unique available lessons');
  for(const click of clicks)click({target:{closest:s=>s==='button'?spanish:null},preventDefault(){}});
  location.hash='#sources';windowEvents.hashchange();
  assert.ok(appHTML.includes('Referencia bibliográfica aportada; libro completo no consultado'));
 }finally{for(const [k,v] of Object.entries(saved)){if(v===undefined)delete globalThis[k];else globalThis[k]=v;}}
});
